#!/usr/bin/env node
// Regenerates apps/web/src/styles/tokens.generated.css from the `website`
// surface of design/tokens/active.json (Open Flow, adopted by DEC-20261024-B).
// The CSS is rendered by the same function that builds the Open Flow kit's
// tokens.css, so the kit specimen and the site cannot disagree; only the font
// URLs differ (the site serves the kit's font files from /fonts/).
//
//   (default) — write tokens.generated.css
//   --check   — diff against the committed file, exit 2 on drift
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { isDirectInvocation, repoRootFrom } from "./design-lib.mjs";
import { loadProvenance, renderTokensCss } from "../design/brand-kit/open-flow/build.mjs";

export const ACTIVE_TOKENS_PATH = "design/tokens/active.json";
export const WEB_TOKENS_PATH = "apps/web/src/styles/tokens.generated.css";

const HEADER = `/* GENERATED by scripts/generate-web-tokens.mjs from design/tokens/active.json surfaces.website — do not edit. */
/* Open Flow, adopted by DEC-20261024-B. Regenerate: npm run design:web-tokens (checked by npm run design:check). */`;

export function loadWebsiteSurface(root) {
  const active = JSON.parse(readFileSync(resolve(root, ACTIVE_TOKENS_PATH), "utf8"));
  const surface = active.surfaces?.website;
  if (!surface) throw new Error(`${ACTIVE_TOKENS_PATH} has no surfaces.website`);
  return surface;
}

export function render(surface) {
  return renderTokensCss(surface, loadProvenance(), { fontBase: "/fonts/", header: HEADER });
}

export function generate(root, { check = false } = {}) {
  const content = render(loadWebsiteSurface(root));
  const outPath = resolve(root, WEB_TOKENS_PATH);
  if (check) {
    if (!existsSync(outPath)) return { stale: true, missing: true, content };
    return { stale: readFileSync(outPath, "utf8") !== content, missing: false, content };
  }
  writeFileSync(outPath, content);
  return { stale: false, missing: false, content };
}

if (isDirectInvocation(import.meta.url)) {
  const root = repoRootFrom(import.meta.url);
  const check = process.argv.includes("--check");
  const result = generate(root, { check });
  if (check && result.stale) {
    console.error(`${WEB_TOKENS_PATH} is ${result.missing ? "missing" : "stale"} — fix: npm run design:web-tokens`);
    process.exit(2);
  }
  console.log(check ? `ok   ${WEB_TOKENS_PATH} matches active.json` : `wrote ${WEB_TOKENS_PATH}`);
}
